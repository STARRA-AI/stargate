/**
 * Text out of .docx and .xlsx, so the Vault page's accept list stops lying.
 *
 * ★ THE BUG THIS CLOSES. `src/app/vault/page.tsx` has advertised
 * `.docx,.xlsx` since the Vault shipped, but `ingestTextFile` had no branch for
 * either — both fell to the `else` and ran `buffer.toString("utf8")`. Both
 * formats are ZIP containers, so what actually got stored as her "facts" was
 * compressed binary. It never threw and never warned; the upload just returned
 * 200 with garbage in it.
 *
 * ★ NO NEW DEPENDENCY. `jszip` 3.10.1 was already on disk as a dependency of
 * `docx` 9.7.1 (which this repo uses to WRITE documents). It is now declared in
 * package.json directly rather than relied on through hoisting — the install was
 * offline and downloaded nothing.
 *
 * ★ REGEX, NOT AN XML PARSER, AND THAT IS A DELIBERATE LIMIT. These two schemas
 * are machine-generated by Office/Pages/Sheets with a narrow, stable shape, and
 * the goal is READABLE TEXT for a prompt, not a faithful document model. What
 * that costs is written into each function below. Nothing here throws: a
 * malformed or unexpected archive returns "" and the caller falls back to the
 * same stored-but-unreadable note the PDF branch already uses.
 */
import JSZip from "jszip";

/** XML entities Office actually emits, plus numeric escapes. */
function decodeEntities(s: string): string {
  return s
    .replace(/&#x([0-9a-fA-F]+);/g, (_, h) => safeCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => safeCodePoint(parseInt(d, 10)))
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, "&"); // LAST, so "&amp;lt;" becomes "&lt;" not "<"
}

function safeCodePoint(n: number): string {
  if (!Number.isFinite(n) || n < 0 || n > 0x10ffff) return "";
  try {
    return String.fromCodePoint(n);
  } catch {
    return "";
  }
}

/** Drop every tag, then decode. Order matters: entities must survive tag removal. */
function stripTags(xml: string): string {
  return decodeEntities(xml.replace(/<[^>]*>/g, ""));
}

/** Collapse runs of 3+ newlines and trim trailing spaces per line. */
function tidy(text: string): string {
  return text
    .split("\n")
    .map((l) => l.replace(/[ \t]+$/, ""))
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

/**
 * .docx -> the body text of word/document.xml.
 *
 * LIMITS, stated rather than discovered later: headers, footers, footnotes,
 * endnotes and comments live in their own parts and are NOT included — only the
 * body. Tables come out one cell per line, because a cell contains paragraphs
 * and honouring both would need real nesting; for reading back to her, one cell
 * per line is legible and unambiguous. Tracked-change deletions (`<w:delText>`)
 * are excluded, so what you get is the document as it currently reads.
 */
export async function docxToText(buffer: Buffer): Promise<string> {
  const zip = await JSZip.loadAsync(buffer);
  const doc = zip.file("word/document.xml");
  if (!doc) return "";
  let xml = await doc.async("string");

  // Deleted text must go before the generic tag strip, contents and all.
  xml = xml.replace(/<w:delText\b[^>]*>[\s\S]*?<\/w:delText>/g, "");
  // Structure -> whitespace, while the tags still exist to mark it.
  xml = xml.replace(/<w:tab\b[^>]*\/?>/g, "\t");
  xml = xml.replace(/<w:br\b[^>]*\/?>/g, "\n");
  xml = xml.replace(/<\/w:p>/g, "\n");

  return tidy(stripTags(xml));
}

/**
 * .xlsx -> every sheet as tab-separated rows under its own name.
 *
 * LIMITS: values are read as STORED, so a date is its serial number and a
 * formula cell gives its cached result, not the formula. Empty cells collapse
 * rather than holding their column position — a row is its non-empty values in
 * order, which is what reads back usefully and is NOT a faithful grid.
 *
 * Sheet names come from xl/workbook.xml in declaration order and are paired with
 * xl/worksheets/sheetN.xml in numeric order. That pairing is right for every
 * file Office and Sheets produce; a hand-assembled archive with mismatched
 * rIds could label a sheet wrong, which is why the name is a heading and never
 * load-bearing.
 */
export async function xlsxToText(buffer: Buffer): Promise<string> {
  const zip = await JSZip.loadAsync(buffer);

  // Shared strings: <si> may hold several <t> runs that concatenate into one value.
  const shared: string[] = [];
  const ssFile = zip.file("xl/sharedStrings.xml");
  if (ssFile) {
    const ss = await ssFile.async("string");
    for (const m of ss.matchAll(/<si\b[^>]*>([\s\S]*?)<\/si>/g)) {
      const runs = [...m[1].matchAll(/<t\b[^>]*>([\s\S]*?)<\/t>/g)].map((t) =>
        decodeEntities(t[1]),
      );
      shared.push(runs.join(""));
    }
  }

  const names: string[] = [];
  const wbFile = zip.file("xl/workbook.xml");
  if (wbFile) {
    const wb = await wbFile.async("string");
    for (const m of wb.matchAll(/<sheet\b[^>]*\bname="([^"]*)"/g)) {
      names.push(decodeEntities(m[1]));
    }
  }

  const sheetFiles = Object.keys(zip.files)
    .filter((n) => /^xl\/worksheets\/sheet\d+\.xml$/.test(n))
    .sort(
      (a, b) =>
        Number(/sheet(\d+)\.xml$/.exec(a)![1]) - Number(/sheet(\d+)\.xml$/.exec(b)![1]),
    );

  const out: string[] = [];
  for (let i = 0; i < sheetFiles.length; i++) {
    const xml = await zip.file(sheetFiles[i])!.async("string");
    const rows: string[] = [];

    for (const r of xml.matchAll(/<row\b[^>]*>([\s\S]*?)<\/row>/g)) {
      const cells: string[] = [];
      // Self-closing <c .../> is an empty cell and is skipped by this pattern.
      for (const c of r[1].matchAll(/<c\b([^>]*)>([\s\S]*?)<\/c>/g)) {
        const attrs = c[1];
        const body = c[2];
        const type = /\bt="([^"]*)"/.exec(attrs)?.[1];

        let value = "";
        if (type === "s") {
          const idx = Number(/<v>([\s\S]*?)<\/v>/.exec(body)?.[1]);
          value = Number.isInteger(idx) ? (shared[idx] ?? "") : "";
        } else if (type === "inlineStr") {
          value = [...body.matchAll(/<t\b[^>]*>([\s\S]*?)<\/t>/g)]
            .map((t) => decodeEntities(t[1]))
            .join("");
        } else {
          value = decodeEntities(/<v>([\s\S]*?)<\/v>/.exec(body)?.[1] ?? "");
        }
        if (value !== "") cells.push(value);
      }
      if (cells.length > 0) rows.push(cells.join("\t"));
    }

    if (rows.length === 0) continue;
    const name = names[i] ?? `Sheet ${i + 1}`;
    out.push(`## ${name}\n${rows.join("\n")}`);
  }

  return tidy(out.join("\n\n"));
}

/** Which office container, if any, this filename is. */
export function officeKind(name: string): "docx" | "xlsx" | null {
  const lower = name.toLowerCase();
  if (lower.endsWith(".docx")) return "docx";
  if (lower.endsWith(".xlsx")) return "xlsx";
  return null;
}
