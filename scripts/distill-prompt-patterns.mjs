#!/usr/bin/env node
/**
 * Distill SECTION STRUCTURE from system_prompts_leaks — tags/patterns only.
 * Never copies Anthropic/OpenAI assistant personality into STARRA.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const LEAKS = path.join(ROOT, "docs/reference/system_prompts_leaks");
const OUT_MD = path.join(ROOT, "docs/reference/PROMPT_STRUCTURE.md");
const OUT_TS = path.join(ROOT, "src/lib/prompt-structure.ts");

const SOURCES = [
  "Anthropic/claude-sonnet-5.md",
  "Anthropic/claude-opus-4.8.md",
  "OpenAI/gpt-5.5-api.md",
  "OpenAI/Codex/codex-full.md",
].map((p) => path.join(LEAKS, p));

function extractTags(text) {
  const tags = new Set();
  const re = /<\/?([a-zA-Z][a-zA-Z0-9_-]{2,40})>/g;
  let m;
  while ((m = re.exec(text))) {
    const t = m[1].toLowerCase();
    if (["html", "body", "div", "span", "p", "br", "b", "i", "ul", "li"].includes(t)) continue;
    tags.add(t);
  }
  return [...tags].sort();
}

function extractHeadings(text) {
  return [...text.matchAll(/^#{1,3}\s+(.+)$/gm)]
    .map((m) => m[1].trim())
    .slice(0, 40);
}

if (!fs.existsSync(LEAKS)) {
  console.error("system_prompts_leaks missing — run scripts/bootstrap-tools.sh");
  process.exit(1);
}

const allTags = new Set();
const report = [];

for (const file of SOURCES) {
  if (!fs.existsSync(file)) {
    report.push(`- missing: ${path.relative(LEAKS, file)}`);
    continue;
  }
  const text = fs.readFileSync(file, "utf8");
  const tags = extractTags(text);
  tags.forEach((t) => allTags.add(t));
  report.push(
    `### ${path.relative(LEAKS, file)}\n- tags (${tags.length}): ${tags.slice(0, 25).join(", ")}${tags.length > 25 ? ", …" : ""}\n- size: ${text.length} chars`,
  );
}

const preferredSections = [
  "identity",
  "tool_use",
  "refusal_handling",
  "tone_and_formatting",
  "proactivity",
  "legal_and_financial_advice",
  "knowledge_cutoff",
  "memory",
].filter((s) => allTags.has(s) || true);

const md = `# Prompt structure distillation

Generated by \`scripts/distill-prompt-patterns.mjs\`.
Source: [system_prompts_leaks](https://github.com/asgeirtj/system_prompts_leaks) (local clone).

## Policy for STARRA

- Steal **structure** (named XML-ish sections, tool discipline, refusal clarity).
- Do **not** steal Anthropic/OpenAI **tone** (warm helper, "happy to help").
- STARRA voice remains operator register from \`STARGATE_DESIGN_SPEC.md\`.

## Preferred section scaffold

${preferredSections.map((s) => `- \`<${s}>\``).join("\n")}

## Observed tags across samples

${[...allTags].slice(0, 80).map((t) => `- ${t}`).join("\n")}

## Per-file notes

${report.join("\n\n")}
`;

fs.writeFileSync(OUT_MD, md, "utf8");

const ts = `/**
 * Distilled prompt STRUCTURE for STARRA.
 * Generated/updated by scripts/distill-prompt-patterns.mjs from system_prompts_leaks.
 * Personality/tone is NOT imported from leaked prompts — only section discipline.
 */

export const PROMPT_SECTION_ORDER = [
  "identity",
  "operator_voice",
  "business_canon",
  "tools",
  "memory_contract",
  "refusal_and_safety",
  "legal_financial_boundary",
  "proactivity",
] as const;

export type PromptSection = (typeof PROMPT_SECTION_ORDER)[number];

/** Structural rules borrowed from industry system-prompt practice (not their wording). */
export const STRUCTURE_RULES = \`
<identity>
You are STARRA, the AI operator inside STARGATE (STARRA LLC). Classic Williams is the human operator. You are not a chatbot product persona.
</identity>

<operator_voice>
Calm. Low. Decisive. Dry. British-neutral or American-neutral — consistent.
Prefer: "Copy." "Standing by." "Two items need you today."
Forbid: "Sure!", "Happy to help", "Great question", "Let me know if you need anything else", emoji, excessive name use.
</operator_voice>

<tools>
When the operator asks to pack/inspect the codebase, use Repomix output if present in context.
When the operator asks to produce video / Silent Shadow shorts / Book of Starra visuals via OpenMontage, queue a job brief (do not claim render finished unless a tool result says so).
Never invent connector status. Report ● connected / ○ available / ◆ error only from provided state.
</tools>

<memory_contract>
Ground advice in Tier-1 (goals/projects/tasks/decisions), memory tiers, and Vault facts when provided.
If context is missing, say so and give the next acquisition step — do not fabricate MRR or deal state.
</memory_contract>

<refusal_and_safety>
Refuse weapon-enabling detail, malware help, and any child-exploitation content. State the principle, not detection mechanics.
For credit/funding: give procedural next steps from STARRA canon; never guarantee approval or coach fraud.
</refusal_and_safety>

<legal_financial_boundary>
Not a lawyer or financial advisor. Dragon Tradar and funding talk stays factual + disclaimers. No income promises.
Silent Shadow stays pseudonymous in public-facing copy. AlphaSurplus stays out of public copy.
</legal_financial_boundary>

<proactivity>
Prefer one clear next move over a menu of options. If ambiguous, pick the reasonable default, state the assumption in one line, proceed.
Confirm before any send/modify/delete on external systems.
</proactivity>
\`.trim();

export function structureBlock(): string {
  return STRUCTURE_RULES;
}
`;

fs.writeFileSync(OUT_TS, ts, "utf8");
console.log("Wrote", path.relative(ROOT, OUT_MD));
console.log("Wrote", path.relative(ROOT, OUT_TS));
